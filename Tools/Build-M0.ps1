param(
    [string]$UnityPath = 'C:\Program Files\Unity\Hub\Editor\6000.6.8f1\Editor\Unity.exe'
)
$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
if (-not (Test-Path -LiteralPath $UnityPath)) { throw "Unity not found: $UnityPath" }
# A separate project prevents interference with the user's open Editor or unsaved scene.
$runId = Get-Date -Format 'yyyyMMdd-HHmmss'
$stagePath = Join-Path $projectRoot ".m0-validation\$runId"
$logDirectory = Join-Path $projectRoot 'Logs\M0'
$buildPath = Join-Path $projectRoot 'Build\Windows-M0\QuaThangNayDa-M0.exe'
New-Item -ItemType Directory -Path $stagePath,$logDirectory -Force | Out-Null
foreach ($folder in @('Assets','Packages','ProjectSettings')) {
    Copy-Item -LiteralPath (Join-Path $projectRoot $folder) -Destination $stagePath -Recurse
}
$logPath = Join-Path $logDirectory "build-$runId.log"
Write-Host "Building isolated M0 project. Log: $logPath"
$arguments = @('-batchmode','-nographics','-quit','-projectPath', ('"' + $stagePath + '"'),
    '-buildTarget','Win64','-executeMethod','QuaThangNayDa.Editor.FoundationTools.BuildBatch',
    '-m0-build-output', ('"' + $buildPath + '"'), '-logFile', ('"' + $logPath + '"'))
$process = Start-Process -FilePath $UnityPath -ArgumentList $arguments -WindowStyle Hidden -PassThru -Wait
if ($process.ExitCode -ne 0) { throw "Unity exited with $($process.ExitCode). Inspect $logPath" }
if (-not (Test-Path -LiteralPath $buildPath)) { throw 'Build executable was not produced.' }
# Import only generated M0 content that does not already exist. Never overwrite user content.
foreach ($relative in @('Assets\_Project\Scenes\Bootstrap.unity.meta',
                       'Assets\_Project\Scenes\Bootstrap.unity',
                       'Assets\_Project\Art\Materials\M0Surface.mat.meta',
                       'Assets\_Project\Art\Materials\M0Surface.mat')) {
    $destination = Join-Path $projectRoot $relative
    if (-not (Test-Path -LiteralPath $destination)) {
        New-Item -ItemType Directory -Path (Split-Path -Parent $destination) -Force | Out-Null
        Copy-Item -LiteralPath (Join-Path $stagePath $relative) -Destination $destination
    }
}
# Preserve GUIDs generated by Unity for new scripts/folders when the main Editor has not imported yet.
$stagedAssets = Join-Path $stagePath 'Assets'
foreach ($meta in Get-ChildItem -LiteralPath $stagedAssets -Filter '*.meta' -Recurse) {
    $relativeMeta = $meta.FullName.Substring($stagePath.Length + 1)
    $targetMeta = Join-Path $projectRoot $relativeMeta
    $targetAsset = $targetMeta.Substring(0, $targetMeta.Length - 5)
    if ((Test-Path -LiteralPath $targetAsset) -and -not (Test-Path -LiteralPath $targetMeta)) {
        Copy-Item -LiteralPath $meta.FullName -Destination $targetMeta
    }
}
Write-Host "M0 Windows build ready: $buildPath"
Write-Host 'Validation project retained under .m0-validation; ignored by Git.'
